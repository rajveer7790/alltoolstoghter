import { writeFileSync } from 'node:fs';
import { INDEXABLE_TOOLS } from '../lib/registry';
import { keywordReport } from '../lib/seo/keywordCheck';
import { canonicalToolPath } from '../lib/toolPolicy';
import { DEEP } from '../lib/seo/deep';
import { OPENERS } from '../lib/seo/openers';

// On-page keyword placement test. It checks where target phrases appear in the page we ship.
// It does NOT measure search volume, rankings, impressions or whether any AI answer cites the page.
const reports = INDEXABLE_TOOLS.map(tool => ({ tool, r: keywordReport(tool) }));
const pct = (n: number, d: number) => (d ? `${Math.round((n / d) * 100)}%` : '–');
const group = (rows: typeof reports) => ({
  n: rows.length,
  title: rows.filter(x => x.r.title).length, description: rows.filter(x => x.r.description).length,
  h1: rows.filter(x => x.r.h1).length, answer: rows.filter(x => x.r.answer).length, heading: rows.filter(x => x.r.heading).length,
  longTotal: rows.reduce((a, x) => a + x.r.long.length, 0), longHit: rows.reduce((a, x) => a + x.r.long.filter(l => l.where.length).length, 0),
});
const full = reports.filter(x => !!DEEP[x.tool.slug]?.shortKeyword);
const openers = reports.filter(x => x.r.source === 'declared' && !DEEP[x.tool.slug]?.shortKeyword);
const declared = [...full, ...openers];
const registry = reports.filter(x => x.r.source === 'registry');
const line = (label: string, g: ReturnType<typeof group>) => `| ${label} | ${g.n} | ${pct(g.title, g.n)} | ${pct(g.description, g.n)} | ${pct(g.h1, g.n)} | ${pct(g.answer, g.n)} | ${pct(g.heading, g.n)} | ${pct(g.longHit, g.longTotal)} |`;
const mark = (b: boolean) => (b ? '✓' : '✗');
const gaps = registry.filter(x => !x.r.title).slice(0, 80);
const out = `# On-page keyword placement report

Generated by \`npm run report:keywords\`. It tests where each tool's **target phrases appear in the shipped page**. It does **not** measure search volume, rankings, impressions, click-through or whether an AI answer cites the page; measure those in Search Console and by checking the live results.

## Coverage by group

| Group | Tools | In title | In description | In H1 | In first 70 words of answer | In a heading | Long-tail phrases found |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${line('Short keyword + 3 long-tail phrases + AI summary', group(full))}
${line('Short keyword in description and opening answer (no long-tail phrases yet)', group(openers))}
${line('Registry keywords only', group(registry))}

## Tools with declared keywords

| Tool | Short keyword | Title | Desc | H1 | Answer | Long-tail phrases (where found) |
| --- | --- | :-: | :-: | :-: | :-: | --- |
${declared.map(({ tool, r }) => `| [${tool.name}](${canonicalToolPath(tool)}) | ${r.short} | ${mark(r.title)} | ${mark(r.description)} | ${mark(r.h1)} | ${mark(r.answer)} | ${r.long.map(l => `${l.phrase} (${l.where.join('+') || 'missing'})`).join('; ')} |`).join('\n')}

## Gaps: tools whose registry keyword is missing from the title (first ${gaps.length})

${gaps.map(({ tool, r }) => `- [${tool.name}](${canonicalToolPath(tool)}): "${r.short}"`).join('\n') || 'None.'}
`;
writeFileSync('docs/KEYWORD_COVERAGE_REPORT.md', out);
console.log(`full ${full.length}, openers ${openers.length}, registry-only ${registry.length}; title gaps ${registry.filter(x => !x.r.title).length}`);
